#!/usr/bin/env python3
"""
BOH License Generator
=====================
Generates customer_features.h (C header) for a specific customer.
This header is #included by boh_features.h and COMPILED INTO boh.dll.
No runtime config file — the license is baked into the binary.

Run: python gen_license.py --customer "ServerName" --features ItemColors,ExtendedNames,PincodeUI
"""

import argparse
import os
from datetime import datetime

ALL_FEATURES = {
    "ItemColors":       ("BOH_ITEM_COLORS",       "Custom item name colors"),
    "ExtendedNames":    ("BOH_EXTENDED_NAMES",    "Extended character names"),
    "PlayerNameColors": ("BOH_PLAYER_NAME_COLORS", "Custom player nameplate colors"),
    "RuneVisual":       ("BOH_RUNE_VISUAL",       "Rune set rendering"),
    "FpsOverlay":       ("BOH_FPS_OVERLAY",       "/fps slash command"),
    "PingOverlay":      ("BOH_PING_OVERLAY",      "/ping slash command"),
    "NpcNameOverlay":   ("BOH_NPC_NAME_OVERLAY",  "Always-show NPC names"),
    "InventoryTabs":    ("BOH_INVENTORY_TABS",    "Image-based inventory tabs"),
    "PincodeUI":        ("BOH_PINCODE_UI",        "In-game PIN keypad"),
    "WeaponSprite":     ("BOH_WEAPON_SPRITE",     "Dual-wield weapon sprite renderer"),
}

def main():
    parser = argparse.ArgumentParser(description="Generate BOH customer_features.h")
    parser.add_argument("--customer", required=True, help="Customer/server name")
    parser.add_argument("--features", default="",
                        help="Comma-separated feature names to enable")
    parser.add_argument("--all", action="store_true",
                        help="Enable all features")
    parser.add_argument("-o", "--output", default="customer_features.h",
                        help="Output file path (default: customer_features.h)")
    args = parser.parse_args()

    if args.all:
        enabled = set(ALL_FEATURES.keys())
    else:
        enabled = set()
        if args.features:
            for f in args.features.split(","):
                f = f.strip()
                if f in ALL_FEATURES:
                    enabled.add(f)
                else:
                    print(f"WARNING: Unknown feature '{f}' — skipping")

    lines = []
    lines.append("// customer_features.h — Per-customer feature flags")
    lines.append("// ==================================================")
    lines.append(f"// Customer : {args.customer}")
    lines.append(f"// Generated: {datetime.now().isoformat()}")
    lines.append("// Generated by gen_license.py. Edit this file, then rebuild.")
    lines.append("// 1 = enabled (paid), 0 = disabled (not paid)")
    lines.append("// This is COMPILED INTO boh.dll — no runtime file to tamper with.")
    lines.append("")

    max_define_len = max(len(info[0]) for info in ALL_FEATURES.values())
    for name, (define, desc) in ALL_FEATURES.items():
        value = "1" if name in enabled else "0"
        lines.append(f"#define {define:<{max_define_len}} {value}")

    lines.append("")

    output = "\n".join(lines)
    out_path = args.output if os.path.isabs(args.output) else os.path.join(os.path.dirname(__file__) or ".", args.output)
    with open(out_path, "w") as f:
        f.write(output)

    print(f"License header written to: {os.path.abspath(out_path)}")
    print(f"Customer: {args.customer}")
    enabled_names = sorted(enabled) if enabled else []
    print(f"Features enabled: {', '.join(enabled_names) if enabled_names else '(none)'}")

if __name__ == "__main__":
    main()
