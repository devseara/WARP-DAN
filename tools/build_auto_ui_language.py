"""Compile the editable Traditional Chinese UI catalog to exact UTF-8 and CP950 bytes."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "Inputs/AutoUI/zh-TW.json"
OUTPUT = CATALOG.with_name("zh-TW.bytes.json")


def compile_catalog():
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    labels = set()
    for name in ("AutoCombatUI", "AutoSupportUI"):
        source = (ROOT / f"Scripts/Patches/{name}.qjs").read_text(encoding="utf-8")
        block = source[source.index("\tconst tabLabels ="):
                       source.index("\tconst controllerPositionRegistry =")]
        labels.update(json.loads(literal) for literal in
                      re.findall(r'"(?:[^"\\]|\\.)*"', block))
    if labels != catalog.keys():
        raise ValueError(f"Catalog mismatch: missing={labels - catalog.keys()}, "
                         f"unused={catalog.keys() - labels}")
    compiled = []
    for english, chinese in catalog.items():
        # Preserve native varargs order, widths, precision, and literal percent signs.
        assert re.findall(r"%(?:\.\d+)?[su%]", english) == re.findall(r"%(?:\.\d+)?[su%]", chinese), english
        encodings = {}
        for key, codec in (("cp950", "cp950"), ("utf8", "utf-8")):
            raw = chinese.encode(codec, errors="strict")
            assert raw.decode(codec) == chinese and b"\0" not in raw, english
            encodings[key] = list(raw)
        # One record per line keeps generated byte tables compact and reviewable.
        compiled.append("  " + json.dumps(english) + ": " + json.dumps(encodings))
    return ("{\n" + ",\n".join(compiled) + "\n}\n").encode("ascii")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = compile_catalog()
    if args.check:
        assert OUTPUT.read_text(encoding="ascii").encode("ascii") == data, "Rebuild the UI byte catalog"
    else:
        OUTPUT.write_bytes(data)
    print("PASS: complete UI catalog, UTF-8/CP950 round trips, native format arguments")
